from transformers import AutoImageProcessor

model_name = "google/vit-base-patch16-224-in21k"
processor = AutoImageProcessor.from_pretrained(model_name)

def transform(batch):
    images = [img.convert("RGB") for img in batch["image"]]
    inputs = processor(images, return_tensors="pt")
    inputs["labels"] = batch["label"]
    return inputs

prepared = ds.with_transform(transform)

import torch
import numpy as np
import evaluate

def collate_fn(batch):
    return {
        "pixel_values": torch.stack([x["pixel_values"] for x in batch]),
        "labels": torch.tensor([x["labels"] for x in batch]),
    }

accuracy = evaluate.load("accuracy")

def compute_metrics(p):
    preds = np.argmax(p.predictions, axis=1)
    return accuracy.compute(predictions=preds, references=p.label_ids)

from transformers import AutoModelForImageClassification

model = AutoModelForImageClassification.from_pretrained(
    model_name,
    num_labels=len(labels),
    id2label=id2label,
    label2id=label2id,
)

from transformers import TrainingArguments, Trainer

args = TrainingArguments(
    output_dir="./vit-beans",
    per_device_train_batch_size=16,
    per_device_eval_batch_size=16,
    num_train_epochs=4,
    learning_rate=3e-5,
    eval_strategy="epoch",
    save_strategy="epoch",
    logging_steps=20,
    load_best_model_at_end=True,
    metric_for_best_model="accuracy",
    remove_unused_columns=False,
    fp16=torch.cuda.is_available(),
    report_to="none",
)

trainer = Trainer(
    model=model,
    args=args,
    data_collator=collate_fn,
    compute_metrics=compute_metrics,
    train_dataset=prepared["train"],
    eval_dataset=prepared["validation"],
)

trainer.train()

from sklearn.metrics import classification_report, ConfusionMatrixDisplay

preds = trainer.predict(prepared["test"])
y_pred = np.argmax(preds.predictions, axis=1)

print("Test accuracy:", (y_pred == preds.label_ids).mean())
print(classification_report(preds.label_ids, y_pred, target_names=labels))

ConfusionMatrixDisplay.from_predictions(
    preds.label_ids, y_pred, display_labels=labels, xticks_rotation=30
)
plt.show()

trainer.save_model("./final-model")
processor.save_pretrained("./final-model")

